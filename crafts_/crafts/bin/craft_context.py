'''
`craft-context` sets up project context for coding agents.

# CTX/AGENTS/CLAUDE Markdown

The program generates AGENTS.md and CLAUDE.md files from other markdown files.
We do this because Claude Code supports `@` syntax file includes while others do not.

Each input is a file named CTX.md. For each one we generate two siblings:
* AGENTS.md, which contains the CTX.md text followed by the contents of each transitively imported file.
* CLAUDE.md, a symlink to CTX.md, because Claude Code expands the imports itself.

The AGENTS.md layout imitates the way Claude Code presents imports to the model.
The `@path` token is left in place and each imported file is appended as a block of the form:
```
Contents of ${path}:

${content}
```

Import syntax is deliberately strict in an attempt to protect against discrepancies between parsers.

Importing a generated AGENTS.md is an error. Import the CTX.md source or one of the files that it imports instead.

# Skills

We also link both .claude/skills and .agents/skills to context/skills, so the same skills are available across platforms.
'''

import re
from argparse import ArgumentParser, RawDescriptionHelpFormatter
from textwrap import dedent
from typing import Iterator

from pithy.filestatus import is_dir, is_file, is_link, path_exists
from pithy.fs import make_dirs, make_link, real_path, walk_files
from pithy.io import outL
from pithy.lex import Lexer
from pithy.path import expand_home_dir, is_path_abs, norm_path, path_dir_or_dot, path_join, path_name, rel_path
from tolkien import Source, Token


ctx_name = 'CTX.md'
agents_name = 'AGENTS.md'
claude_name = 'CLAUDE.md'
skills_dir = 'context/skills'
skills_link_dirs = ('.claude', '.agents')

max_import_depth = 5 # Claude Code documents a maximum of five hops.

generated_warning = f'<!-- Generated by craft-context from {ctx_name}. Do not edit; edit {ctx_name} and the files it imports. -->'


def main() -> None:
  arg_parser = ArgumentParser(prog='craft-context',
    description='Configures a repository for agent-agnostic context files, skills, etc.',
    epilog=dedent('''
    Put agent instructions in CTX.md; these will be symlinked to both AGENTS.md and CLAUDE.md.
    Put cross-platform skills in context/skills; this directory will be symlinked to both .agents/skills and .claude/skills.

    Add this conventional rule to your justfile:
    ```
    ctx:
      craft-context
    ```'''),
    formatter_class=RawDescriptionHelpFormatter)

  arg_parser.add_argument('paths', nargs='*', default=['.'], help=f'Input {ctx_name} files, or directories to search for them.')
  args = arg_parser.parse_args()

  src_paths = find_src_paths(args.paths)
  roots = {path if is_dir(path, follow=True) else path_dir_or_dot(path) for path in args.paths}
  for root in sorted(roots):
    update_skills_links(root)
  for src in src_paths:
    process_path(src)


def find_src_paths(paths:list[str]) -> list[str]:
  'Expand the input paths into a list of CTX.md source paths.'
  srcs:list[str] = []
  for path in paths:
    if is_dir(path, follow=True):
      srcs.extend(sorted(p for p in walk_files(path, file_exts=['.md']) if path_name(p) == ctx_name))
    elif not path_exists(path, follow=True):
      exit(f'craft-context error: input path does not exist: {path}')
    elif path_name(path) != ctx_name:
      exit(f'craft-context error: input file is not named {ctx_name}: {path}')
    else:
      srcs.append(path)
  return srcs


def process_path(src:str) -> None:
  'Generate the AGENTS.md file and the CLAUDE.md symlink for the CTX.md file at `src`.'
  dir = path_dir_or_dot(src)
  root_text = read_src(src)
  blocks = [generated_warning, root_text]
  emitted = {real_path(src)}
  expand_imports(src, text=root_text, out_dir=dir, blocks=blocks, emitted=emitted, depth=0)

  out_path = path_join(dir, agents_name)
  if update_file(out_path, '\n\n'.join(blocks) + '\n'):
    outL(f'craft-context: wrote {out_path}')

  link_path = path_join(dir, claude_name)
  if update_link(orig=src, link=link_path):
    outL(f'craft-context: linked {link_path} -> {path_name(src)}')


def update_skills_links(root:str) -> None:
  'Create cross-platform skills links under a command-line input root.'
  skills_orig = path_join(root, skills_dir)
  skills_links = [path_join(root, link_dir, 'skills') for link_dir in skills_link_dirs]
  for link in skills_links:
    validate_link(orig=skills_orig, link=link)
  make_dirs(skills_orig)
  for link_dir, link in zip(skills_link_dirs, skills_links, strict=True):
    make_dirs(path_join(root, link_dir))
    if update_link(orig=skills_orig, link=link):
      outL(f'craft-context: linked {link} -> ../{skills_dir}')


def expand_imports(src:str, text:str, *, out_dir:str, blocks:list[str], emitted:set[str], depth:int) -> None:
  'Append a block for each file imported by `src`, recursively, in depth-first order.'
  source = Source(name=src, text=text)
  for token, import_path in scan_imports(source):
    path = resolve_import(source, token, import_path)
    real = real_path(path)
    if real in emitted: continue # Claude Code dedups repeated imports; a cycle terminates here.
    emitted.add(real)
    if depth >= max_import_depth:
      source.fail((token, f'import exceeds the maximum depth of {max_import_depth}.'))
    dep_text = read_src(path)
    if dep_text.startswith(generated_warning):
      source.fail((token, f'import path is a generated file: {path}.\n'
        f'  Import the {ctx_name} source or one of the files that it imports;'
        f' the imports of a generated file are relative to the wrong directory.'))
    blocks.append(f'Contents of {rel_path(path, start=out_dir)}:\n\n{dep_text}')
    expand_imports(path, text=dep_text, out_dir=out_dir, blocks=blocks, emitted=emitted, depth=depth+1)


def resolve_import(source:Source[str], token:Token, import_path:str) -> str:
  'Resolve an import path against the directory of the importing file.'
  path = expand_home_dir(import_path)
  if not is_path_abs(path): path = path_join(path_dir_or_dot(source.name), path)
  path = norm_path(path)
  if not is_file(path, follow=True):
    source.fail((token, f'import path does not exist: {path}'))
  return path


# Lexing.

# A code fence line: a run of three or more backticks or tildes, possibly indented, possibly followed by an info string.
fence_line_re = re.compile(r'(?m)^[ \t]*(?P<fence>`{3,}|~{3,})(?P<info>[^\n]*)$')

# Characters that we accept in an import path. Anything else is ambiguous.
import_path_re = re.compile(r'[\w./~+-]+')

md_lexer = Lexer(patterns=dict(
  newline   = r'\n',
  # A code span is a run of backticks, matching content, and a closing run of exactly the same length.
  code_span = r'(?P<ticks>`+)(?:[^`\n]+|(?!(?P=ticks)(?!`))`+|\n(?![ \t]*\n))+?(?P=ticks)(?!`)',
  backtick  = r'`+', # Only matches backticks that did not form a code span.
  indent    = r'(?m:^(?:\ {4,}|\t+)(?=\S))', # A line indented far enough that markdown might read it as a code block.
  at        = r'@[^\s`]*',
  text      = r'[^@`\n]+',
))

dropped_kinds = frozenset({'newline', 'code_span', 'text'})


def scan_imports(source:Source[str]) -> Iterator[tuple[Token,str]]:
  'Yield the `@` import tokens of `source`, paired with their path text, ignoring code fences and code spans.'
  for pos, end in scan_prose_spans(source):
    for token in md_lexer.lex(source, pos=pos, end=end, drop=dropped_kinds):
      if token.pos >= end: break # Defensive: the lexer patterns should never match past the end of the span.
      if token.kind == 'backtick':
        source.fail((token, 'unmatched backtick; a code span must be closed by an equal length run of backticks.'))
      if token.kind == 'indent':
        if starts_indented_code(source, token.pos):
          source.fail((token, 'indented code block; use a fenced code block instead.'))
        continue # Otherwise this is a continuation line of a list item or paragraph.
      assert token.kind == 'at', token
      yield (token, validate_import(source, token))


def starts_indented_code(source:Source[str], pos:int) -> bool:
  'Test whether an indent at `pos` would begin a markdown indented code block, which requires a preceding blank line.'
  if pos == 0: return True
  prev_line = source.text[source.get_line_start(pos-1):pos-1]
  return not prev_line.strip()


def scan_prose_spans(source:Source[str]) -> list[tuple[int,int]]:
  'Return the spans of `source` that lie outside of fenced code blocks.'
  text = source.text
  spans:list[tuple[int,int]] = []
  pos = 0
  opening:re.Match|None = None
  for m in fence_line_re.finditer(text):
    if opening is None:
      spans.append((pos, m.start()))
      opening = m
    elif closes_fence(opening, m):
      pos = m.end()
      opening = None
    #^ Otherwise the line is content of the open block; a mismatched fence cannot close it.
  if opening is not None:
    source.fail((Token(pos=opening.start(), end=opening.end()), 'unterminated code fence.'))
  spans.append((pos, len(text)))
  return spans


def closes_fence(opening:re.Match, m:re.Match) -> bool:
  'Test whether the fence line `m` closes the block opened by `opening`.'
  fence = m['fence']
  opening_fence = opening['fence']
  return fence[0] == opening_fence[0] and len(fence) >= len(opening_fence) and not m['info'].strip()


def validate_import(source:Source[str], token:Token) -> str:
  'Validate an `@` token and return the import path text. Any ambiguity is a hard error.'
  text = source.text
  path = text[token.pos+1:token.end]

  if token.pos > 0 and not text[token.pos-1].isspace():
    source.fail((token, 'ambiguous `@`; an import must be preceded by whitespace. Enclose other uses in backticks.'))

  if not path:
    source.fail((token, 'lone `@`. Enclose non-import uses in backticks.'))
  if not import_path_re.fullmatch(path):
    source.fail((token, f'ambiguous import path: {path!r}. Enclose non-import uses in backticks.'))
  if path.endswith('.'):
    source.fail((token, f'ambiguous import path: {path!r}; a trailing dot may be sentence punctuation.'))
  return path


# File output.

def read_src(path:str) -> str:
  'Read a source file, trimmed of surrounding whitespace.'
  with open(path) as f:
    return f.read().strip()


def update_file(path:str, text:str) -> bool:
  'Write `text` to `path` if it differs from the current contents. Return True if the file was written.'
  try:
    with open(path) as f:
      if f.read() == text: return False
  except FileNotFoundError: pass
  with open(path, 'w') as f:
    f.write(text)
  return True


def validate_link(orig:str, link:str) -> None:
  'Exit with an error if `link` exists but does not point to `orig`.'
  if path_exists(link, follow=False) and (not is_link(link) or real_path(link) != real_path(orig)):
    exit(f'craft-context error: cannot create symlink to {orig}; path already exists: {link}')


def update_link(orig:str, link:str) -> bool:
  'Create a symlink at `link` pointing to `orig` if it is not already present. Return True if the link was created.'
  validate_link(orig=orig, link=link)
  if path_exists(link, follow=False): return False
  make_link(orig, link=link)
  return True


if __name__ == '__main__': main()
