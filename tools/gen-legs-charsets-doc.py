from pithy.unicode import abbreviated_planes
from pithy.unicode.categories import unicode_category_aliases
from pithy.unicode.charsets import unicode_charsets
from pithy.unicode.data import blocks, unicode_version


def main() -> None:
  print('<!-- Dedicated to the public domain under CC0: https://creativecommons.org/publicdomain/zero/1.0/. -->')
  print('<!-- Generated by tools/gen-legs-charsets-doc.py; do not edit. -->')
  print()
  print('# Named Character Classes')
  print()
  print(f'This reference uses the bundled Unicode {unicode_version} data and the exact registry used by the Legs parser.')
  print('Regenerate it from the repository root with `make gen-grammars`.')
  print()
  print('Names are case-sensitive and begin with `$`: `$Letter`, `$L` and `$Ascii_Letter` are examples.')
  print('Each reference matches one character; add `+` to match a run.')
  print('References denote character sets, not other pattern definitions.')
  print()
  print('Inside brackets, juxtaposition forms a union, `&` an intersection, `-` a difference, and `^` a symmetric difference.')
  print('For example, `[$Ascii_Letter _]` includes ASCII letters and underscore; `[$Letter - $Ascii]` excludes ASCII letters.')
  print('Use nested brackets to make grouping explicit.')
  print('The escape `\\s` means a literal ASCII space, not a Unicode whitespace class.')
  print()
  print('Category aliases include short codes, full names and unambiguous first words.')
  print('`Decimal` is the exception: it is the ASCII convenience class 0-9, not an alias of `Decimal_Number`/`Nd`.')
  print('ASCII category subsets have names such as `Ascii_Letter` and aliases such as `AL`; empty subsets are omitted.')
  print('Block names describe code-point intervals, including any unassigned positions within them.')
  print('Plane classes cover the bundled block ranges rounded to 4096-code-point boundaries, excluding surrogates;')
  print('they do not necessarily cover every position in a plane.')
  print('Surrogate classes are listed in the registry but cannot match valid UTF-8 input.')
  print()
  print('Convenience classes include `Binary`/`Bin` (0-1), `Quaternary`/`Quat` (0-3), `Octal`/`Oct` (0-7),')
  print('`Decimal`/`Dec` (0-9), and `Hexadecimal`/`Hex` (0-9, A-F, a-f).')
  print('`Visible`/`V` combines L, M, N, P and S; `Readable`/`R` also includes Z.')
  print('`Ascii_Visible`/`AV` and `Ascii_Readable`/`AR` restrict those sets to ASCII.')
  print('`Control_0`/`C0` covers U+0000-U+001F; `Control_1`/`C1` covers U+0080-U+009F.')
  print('`Ascii`/`A` covers U+0000-U+007F. `Other_Encodable`/`CE` is category C without surrogates.')
  print()
  print('The table lists every accepted name. Counts include all code points in the class, including unencodable surrogates.')
  print('Interval endpoints are inclusive.')
  print()
  print('| Name | Definition | Code points |')
  print('| --- | --- | ---: |')
  for name, ranges in sorted(unicode_charsets.items()):
    if cat := unicode_category_aliases.get(name):
      desc = cat.desc.replace('|', '\\|')
    elif name in blocks:
      low, end = blocks[name]
      desc = f'Block U+{low:04X}-U+{end - 1:04X}'
    elif name in abbreviated_planes:
      desc = 'Plane class (see above)'
    elif name.startswith('Ascii_') or name.startswith('A') and name[1:] in unicode_category_aliases:
      desc = 'ASCII subset'
    else:
      desc = 'Convenience class (see above)'
    count = sum(end - low for low, end in ranges)
    print(f'| `${name}` | {desc} | {count} |')


if __name__ == '__main__': main()
