'''
The runtime for generated Python lexers.
A generated lexer is a subclass of `DictLexerBase` that holds the tables for one grammar.
'''

__version__ = '0.0.5'

from collections import deque
from typing import Any, ClassVar, Collection, Container, Iterator

from tolkien import Source, Token


_context_keywords_ = ['byte lexer', 'lexer', 'lexer generator', 'lexer modes', 'lexical analysis', 're.compile',
  'regular expressions', 'scanner', 'tokenization', 'tokenizer']


StateTransitions = dict[int,dict[int,int]] # state -> byte -> dst_state.
MatchStateKinds = dict[int,str] # state -> token kind.
ModeData = tuple[int,StateTransitions,MatchStateKinds] # start_node, state_transitions, match_state_kinds.

KindModeTransitions = dict[str,tuple[str,str]]
ModeTransitions = dict[str,KindModeTransitions]


class LexerBase(Iterator[Token]):
  '''
  The base class of generated Python lexers.
  An instance is an iterator of the tokens of a source.
  A lexer class conforms to `tolkien.LexerProtocol` by means of `kinds` and `lex`, so it can be passed to `pithy.parse.Parser`.
  '''

  mode_transitions:ModeTransitions
  mode_line_breaks:ClassVar[dict[str,str]] = {} # The line break kind of each line-aware mode.
  mode_line_ignores:ClassVar[dict[str,frozenset[str]]] = {} # The kinds that do not make a line count, per line-aware mode.
  mode_indent_spaces:ClassVar[dict[str,str]] = {} # The kind whose token at the start of a line is the indentation, per indent-aware mode.
  pattern_descs:dict[str,str]
  kinds:ClassVar[frozenset[str]] = frozenset() # The token kinds, excluding `invalid` and `incomplete`.


  def __init_subclass__(cls, **kwargs:Any) -> None:
    super().__init_subclass__(**kwargs)
    pattern_descs = cls.__dict__.get('pattern_descs')
    if pattern_descs is not None: cls.kinds = frozenset(pattern_descs) - {'invalid', 'incomplete'}


  @classmethod
  def lex(cls, source:Source[bytes], slc:slice|None=None, *, mode:str|None=None, drop:Container[str]=(), eot:bool=False
   ) -> Iterator[Token]:
    '''
    Lex `source`, yielding tokens. See `tolkien.LexerProtocol`.
    `mode` defaults to `main`.
    '''
    lexer = cls(source, slc, mode=(mode or 'main'))
    for token in lexer:
      if token.kind not in drop: yield token
    if eot: yield Token(pos=lexer.end, end=lexer.end, mode=lexer.stack[-1][0], kind='end_of_text')


  def __init__(self, source:Source[bytes], slc:slice|None=None, mode:str='main'):
    '''
    Create a lexer for `source`.
    If `slc` is provided then only that range of the text is lexed; no token extends past its end.
    `mode` is the mode in which lexing starts.
    Together these allow a parser that frames the text by other means to lex each framed range with the appropriate mode.
    '''
    if not isinstance(source.text, bytes):
      raise TypeError(f'legs lexers require a source with `bytes` text; received {type(source.text).__name__}: {source!r}')
    pos, end, step = (slc or slice(None)).indices(len(source.text))
    if step != 1: raise ValueError(f'slice step is not supported: {slc!r}')
    if mode not in self.mode_names(): raise ValueError(f'unknown mode: {mode!r}; modes: {sorted(self.mode_names())}')
    self.source = source
    self.pos = pos
    self.end = max(pos, end)
    self.stack:list[tuple[str,str|None]] = [(mode, None)] # [(mode, pop_kind)].
    self.pending = deque[Token]() # Tokens to return before lexing further.
    self.held:list[Token] = [] # The leading tokens of a line in an indent-aware mode, held until the line is known to count.
    self.line_counts = False # The current line holds a counting token, in a line-aware mode.
    self.is_line_start = True
    self.levels = [b''] # The indentation text of each open level.

  @classmethod
  def mode_names(cls) -> Collection[str]:
    'The names of the modes of the lexer.'
    raise NotImplementedError

  def __iter__(self) -> Iterator[Token]: return self

  def __next__(self) -> Token: raise NotImplementedError


class DictLexerBase(LexerBase):
  '''
  The base class of table-driven lexers, as generated by the `python` target.
  `mode_data` holds the DFA of each mode.
  `mode_commit_nodes` holds the nodes of each mode that follow a commitment barrier.
  Each token is the longest match. On reaching a commit node, the lexer forgets the matches found so far in the token.
  In a line-aware mode, an empty `end_of_line` token precedes the line break of each line that holds another token,
  and ends an unterminated last line. Tokens of the mode's line ignore kinds do not count.
  In an indent-aware mode, empty `indent` and `dedent` tokens mark the changes of indentation between counting lines.
  Indentation is compared as text; see `LexMode` in `pithy.lex` for the rule, which is the same.
  '''

  mode_data:dict[str,ModeData]
  mode_commit_nodes:ClassVar[dict[str,frozenset[int]]] = {}

  @classmethod
  def mode_names(cls) -> dict[str,ModeData]: return cls.mode_data

  def __next__(self) -> Token:
    while not self.pending:
      if self.pos == self.end: # Done; flush the line structure.
        mode = self.stack[-1][0]
        if self.held:
          self.pending.extend(self.held)
          self.held.clear()
        elif self.line_counts:
          self.line_counts = False
          self.pending.append(Token(pos=self.end, end=self.end, mode=mode, kind='end_of_line'))
        elif len(self.levels) > 1:
          self.levels.pop()
          self.pending.append(Token(pos=self.end, end=self.end, mode=mode, kind='dedent'))
        else: raise StopIteration
      else:
        self._lex_token()
    return self.pending.popleft()


  def _lex_token(self) -> None:
    'Lex one token and add it to `pending`, with any empty tokens that the line structure requires, or hold it.'
    text = self.source.text
    len_text = self.end
    pos = self.pos
    mode, pop_kind = self.stack[-1]
    mode_start, transitions, match_node_kinds = self.mode_data[mode]

    commit_nodes = self.mode_commit_nodes.get(mode, ())
    state = mode_start
    end = None
    kind = 'incomplete'
    while pos < len_text:
      byte = text[pos]
      try: state = transitions[state][byte]
      except KeyError: break
      else: # advance.
        pos += 1
        if state in commit_nodes:
          end = None
          kind = 'incomplete'
        try: kind = match_node_kinds[state]
        except KeyError: pass
        else: end = pos
    # Matching stopped or reached end of text.
    token_pos = self.pos
    if end is None: # Never reached a match state.
      assert kind == 'incomplete'
      end = pos
    assert token_pos < end # Token cannot be zero length. TODO: support zero-length tokens?
    self.pos = end # Advance lexer state.
    # Check for mode transition.
    if kind == pop_kind:
      self.stack.pop()
    else:
      try: child_frame = self.mode_transitions[mode][kind]
      except KeyError: pass
      else: self.stack.append(child_frame)
    token = Token(pos=token_pos, end=end, mode=mode, kind=kind)
    pending = self.pending
    line_break = self.mode_line_breaks.get(mode)
    if line_break is None: # The mode is not line-aware.
      pending.append(token)
    elif kind == line_break:
      pending.extend(self.held)
      self.held.clear()
      if self.line_counts: pending.append(Token(pos=token_pos, end=token_pos, mode=mode, kind='end_of_line'))
      pending.append(token)
      self.line_counts = False
      self.is_line_start = True
    elif kind in self.mode_line_ignores.get(mode, ()):
      if self.is_line_start and mode in self.mode_indent_spaces: self.held.append(token) # The line may not count.
      else: pending.append(token)
    else: # The token counts.
      if self.is_line_start and mode in self.mode_indent_spaces:
        held = self.held
        space_token = held[0] if held and held[0].kind == self.mode_indent_spaces[mode] else None
        space = text[space_token.slc] if space_token else b''
        levels = self.levels
        if space != levels[-1]:
          count_dedents = 0
          while not space.startswith(levels[-1]):
            levels.pop()
            count_dedents += 1
          if len(space) > len(levels[-1]): # Deeper than the innermost remaining level.
            assert space_token is not None
            levels.append(space)
            at = space_token.pos
            pending.extend(Token(pos=at, end=at, mode=mode, kind='dedent') for _ in range(count_dedents))
            pending.append(Token(pos=at, end=at, mode=mode, kind='indent'))
            pending.extend(held)
          else:
            pending.extend(held)
            pending.extend(Token(pos=token_pos, end=token_pos, mode=mode, kind='dedent') for _ in range(count_dedents))
          held.clear()
      pending.extend(self.held)
      self.held.clear()
      pending.append(token)
      self.line_counts = True
      self.is_line_start = False
