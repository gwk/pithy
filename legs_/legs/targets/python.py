'''
Write Python lexers: the table-driven `python` target.
'''

import re
from typing import TypedDict

from pithy.optional import unwrap
from pithy.reprs import repr_ml
from pithy.strings import render_template

from .. import ModeData, ModeTransitions
from ..dfa import DFA


_context_keywords_ = ['code generation', 'lexer generator', 'source generation', 'table driven lexer']


class OutputOpts(TypedDict):
  'The command options shared by the source code output functions.'
  patterns_path:str|None
  type_prefix:str


def output_python(path:str, dfas:list[DFA], mode_transitions:ModeTransitions,
  pattern_descs:dict[str, str], license:str, *, patterns_path:str|None, type_prefix:str) -> None:
  'Write a table-driven lexer class to `path`. The class is a subclass of `DictLexerBase` that holds the DFA of each mode.'

  mode_data:dict[str,ModeData] = {}

  for dfa in dfas:
    mode = dfa.name
    match_node_kinds = { match_node : unwrap(dfa.match_kind(match_node)) for match_node in dfa.match_nodes }
    kinds = { kind : py_safe_sym(kind) for kind in dfa.pattern_kinds }
    kinds['incomplete'] = 'incomplete'
    assert len(kinds) == len(set(kinds.values()))
    mode_data[mode] = (dfa.start_node, dfa.transitions, match_node_kinds)

  with open(path, 'w', encoding='utf8') as f:
    src = render_template(template,
      Name=type_prefix,
      license=comment_lines(license, '# '),
      mode_data=repr_ml(mode_data, indent=1),
      mode_commit_nodes=repr({dfa.name: dfa.commit_nodes for dfa in dfas if dfa.commit_nodes}),
      mode_transitions=repr_ml(mode_transitions, indent=1),
      pattern_descs=repr_ml(pattern_descs, indent=1),
      patterns_path=patterns_path,
    )
    f.write(src)


template = '''${license}
# This file was generated by legs from ${patterns_path}.

from legs import DictLexerBase, ModeData, ModeTransitions


class ${Name}Lexer(DictLexerBase):

  pattern_descs:dict[str,str] = ${pattern_descs}

  mode_transitions:ModeTransitions = ${mode_transitions}

  mode_data:dict[str,ModeData] = ${mode_data}

  mode_commit_nodes = ${mode_commit_nodes}

'''


def comment_lines(text:str, prefix:str) -> str:
  'Prefix each line of `text` so that multiline text, such as a license, is emitted as comments.'
  return '\n'.join((prefix + line).rstrip() for line in text.split('\n'))


def py_safe_sym(name:str) -> str:
  'Return `name` changed as necessary to be a valid Python identifier.'
  name = re.sub(r'[^\w]', '_', name)
  if name[0].isdigit():
    name = '_' + name
  if name in py_reserved_syms:
    name += '_'
  return name


py_reserved_syms = {
  'False',
  'class',
  'finally',
  'is',
  'return',
  'None',
  'continue',
  'for',
  'lambda',
  'try',
  'True',
  'def',
  'from',
  'nonlocal',
  'while',
  'and',
  'del',
  'global',
  'not',
  'with',
  'as',
  'elif',
  'if',
  'or',
  'yield',
  'assert',
  'else',
  'import',
  'pass',
  'break',
  'except',
  'in',
  'raise',
}
