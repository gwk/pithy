'''
Write Swift lexers: the `swift` target.
The generated lexer is a switch statement over the DFA nodes and input bytes. It requires `legs_base.swift`.
'''

import re
from collections import defaultdict
from typing import Any, Iterable

from pithy.iterable import closed_int_intervals
from pithy.strings import render_template

from .. import ModeTransitions
from ..dfa import DFA
from .python import comment_lines


_context_keywords_ = ['code generation', 'lexer generator', 'source generation', 'string escaping', 'swift literals']


def output_swift(path:str, dfas:list[DFA], mode_transitions:ModeTransitions, mode_line_breaks:dict[str,str],
  mode_line_ignores:dict[str,frozenset[str]], mode_indent_spaces:dict[str,str],
 pattern_descs:dict[str,str], license:str, *, patterns_path:str|None, type_prefix:str) -> None:
  'Generate and write a swift lexer to a file at `path`.'

  # Create safe mode names.
  modes = { dfa.name : swift_safe_sym(dfa.name) for dfa in dfas }
  mode_case_defs = [f'case {modes[dfa.name]} = {dfa.start_node}' for dfa in dfas]

  kind_syms = swift_kind_syms(pattern_descs)
  token_kind_case_defs = [f'case {sym}' for sym in sorted(kind_syms.values())]

  # Token kind descriptions.
  def pattern_desc(kind:str) -> str: return swift_repr(pattern_descs[kind])
  token_kind_case_descs = [f'case .{sym}: return {pattern_desc(kind)}' for kind, sym in sorted(kind_syms.items())]

  # Mode transitions dictionary.

  def mode_trans_dict(d:dict[str,tuple[str,str]]) -> dict:
    return {SwiftEnum(parent_kind): (SwiftEnum(child_mode), SwiftEnum(child_kind))
      for parent_kind, (child_mode, child_kind) in d.items()}

  mode_transitions_dict = {SwiftEnum(modes[name]):mode_trans_dict(d) for name, d in mode_transitions.items()}
  mode_line_breaks_dict = {SwiftEnum(modes[name]):SwiftEnum(kind) for name, kind in mode_line_breaks.items()}
  mode_line_ignores_dict = {SwiftEnum(modes[name]):[SwiftEnum(kind) for kind in sorted(kinds)] for name, kinds in mode_line_ignores.items()}
  mode_indent_spaces_dict = {SwiftEnum(modes[name]):SwiftEnum(kind) for name, kind in mode_indent_spaces.items()}

  # State cases.

  def byte_case_patterns(chars:list[int]) -> list[str]:
    def fmt(l:int, h:int) -> str:
      if l == h: return hex(l)
      return hex(l) + (', ' if l + 1 == h else '...') + hex(h)
    return [fmt(*r) for r in closed_int_intervals(chars)]

  def byte_case(dfa:DFA, chars:list[int], dst:int) -> str:
    pattern_kind = dfa.match_kind(dst)
    sym = None if pattern_kind is None else kind_syms.get(pattern_kind)
    return 'case {chars}: state = {dst}{suffix}'.format(
      chars=', '.join(byte_case_patterns(chars)),
      dst=dst,
      suffix=('; last = -1; kind = .incomplete' if dst in dfa.commit_nodes else '')
        + (f'; last = pos; kind = .{sym}' if sym else ''))

  def byte_cases(dfa:DFA, node:int) -> list[str]:
    dst_chars = defaultdict[int, list[int]](list)
    for char, dst in sorted(dfa.transitions[node].items()):
      dst_chars[dst].append(char)
    dst_chars_sorted = sorted(dst_chars.items(), key=lambda p: p[1])
    return [byte_case(dfa, chars, dst) for dst, chars in dst_chars_sorted]

  def transition_code(dfa:DFA, node:int) -> str:
    d = dfa.transitions[node]
    if not d: return 'break loop' # no transitions.
    return render_template('''switch byte {
        ${byte_cases}
        default: break loop
        }''',
      byte_cases='\n        '.join(byte_cases(dfa, node)))

  def state_case(dfa:DFA, node:int) -> str:
    mode = dfa.name
    kind = dfa.match_kind(node)
    if kind:
      desc = kind
    elif node in dfa.pre_match_nodes:
      desc = f'{mode} pre-match'
    else:
      desc = f'{mode} post-match'
    return 'case {node}: // {desc}.\n        {transition_code}'.format(
      desc=desc,
      node=node,
      transition_code=transition_code(dfa, node))

  state_cases = [state_case(dfa, node) for dfa in dfas for node in sorted(dfa.transitions.keys())]

  with open(path, 'w', encoding='utf8') as f:
    src = render_template(template,
      Name=type_prefix,
      license=comment_lines(license, '// '),
      mode_case_defs='\n  '.join(mode_case_defs),
      mode_default=(' = .main' if 'main' in modes else ''), # A grammar without a `main` mode requires an explicit start mode.
      mode_transitions_dict=swift_repr(mode_transitions_dict, indent=2),
      mode_line_breaks_dict=swift_repr(mode_line_breaks_dict, indent=2),
      mode_line_ignores_dict=swift_repr(mode_line_ignores_dict, indent=2),
      mode_indent_spaces_dict=swift_repr(mode_indent_spaces_dict, indent=2),
      patterns_path=patterns_path,
      state_cases='\n      '.join(state_cases),
      token_kind_case_defs='\n  '.join(token_kind_case_defs),
      token_kind_case_descs='\n    '.join(token_kind_case_descs),
    )
    f.write(src)


template = r'''${license}
// This file was generated by legs from ${patterns_path}.

import Foundation


public enum ${Name}LexMode: Int, Comparable {
  ${mode_case_defs}

  public var startState: Int { return rawValue }

  public static func < (l: ${Name}LexMode, r: ${Name}LexMode) -> Bool { return l.rawValue < r.rawValue }
}


public enum ${Name}TokenKind: Int, Comparable, CustomStringConvertible {
  ${token_kind_case_defs}

  public static func < (l: ${Name}TokenKind, r: ${Name}TokenKind) -> Bool { return l.rawValue < r.rawValue }

  public var description: String {
    switch self {
    ${token_kind_case_descs}
    }
  }
}


public struct ${Name}Lexer: Sequence, IteratorProtocol {

  public typealias Element = Token<${Name}TokenKind>
  public typealias Iterator = ${Name}Lexer

  public let source: Source

  private var stack: [(${Name}LexMode, ${Name}TokenKind?)]
  private var pos: Int
  private let end: Int
  private var lineIdx: Int // The line index of `pos`.
  private var pending: [Token<${Name}TokenKind>] = [] // Tokens to return before lexing further, in order.
  private var pendingIdx = 0 // The index of the next pending token.
  private var held: [Token<${Name}TokenKind>] = [] // The leading tokens of a line in an indent-aware mode, held until the line is known to count.
  private var lineCounts = false // The current line holds a counting token, in a line-aware mode.
  private var isLineStart = true
  private var levels: [Range<Int>] = [0..<0] // The range of the indentation text of each open level.

  // If `range` is provided then only that range of the text is lexed; no token extends past its end.
  // `mode` is the mode in which lexing starts.
  // Together these allow a parser that frames the text by other means to lex each framed range with the appropriate mode.
  public init(source: Source, range: Range<Int>? = nil, mode: ${Name}LexMode${mode_default}) {
    let range = range ?? 0..<source.text.count
    precondition(range.lowerBound >= 0 && range.upperBound <= source.text.count,
      "${Name}Lexer: range is out of bounds: \(range)")
    self.source = source
    self.stack = [(mode, nil)]
    self.pos = range.lowerBound
    self.end = range.upperBound
    self.lineIdx = source.getLineIndex(pos: range.lowerBound)
  }

  public mutating func next() -> Token<${Name}TokenKind>? {
    while pendingIdx == pending.count {
      pending.removeAll(keepingCapacity: true)
      pendingIdx = 0
      if self.pos == end { // Done; flush the line structure.
        let lineIdx = self.lineIdx
        let linePos = (lineIdx == 0) ? 0 : source.newlinePositions[lineIdx - 1] + 1
        if !held.isEmpty {
          pending.append(contentsOf: held)
          held.removeAll()
        } else if lineCounts {
          lineCounts = false
          pending.append(Token(pos: end, end: end, linePos: linePos, lineIdx: lineIdx, kind: .end_of_line))
        } else if levels.count > 1 {
          levels.removeLast()
          pending.append(Token(pos: end, end: end, linePos: linePos, lineIdx: lineIdx, kind: .dedent))
        } else {
          return nil
        }
      } else {
        lexToken()
      }
    }
    let token = pending[pendingIdx]
    pendingIdx += 1
    return token
  }

  // Lex one token and append it to `pending`, with any empty tokens that the line structure requires, or hold it.
  private mutating func lexToken() {
    let (mode, popKind) = self.stack.last!
    let newlinePositions = source.newlinePositions
    let lineIdx = self.lineIdx
    let linePos = (lineIdx == 0) ? 0 : newlinePositions[lineIdx - 1] + 1

    var pos = self.pos
    var state = mode.startState
    var last: Int = -1
    var kind: ${Name}TokenKind = .incomplete

    loop: while pos < end {
      let byte = source.text[pos]

      switch state {

      ${state_cases}

      default: fatalError("${Name}Lexer.next: impossible state: \(state)")
      }
      pos += 1
    }

    let tokenPos = self.pos
    let tokenEnd:Int
    if (last == -1) {
      tokenEnd = pos
      assert(kind == .incomplete)
    } else {
      tokenEnd = last + 1
    }
    assert(tokenPos < tokenEnd, "tokenPos: \(tokenPos); tokenEnd: \(tokenEnd)")
    self.pos = tokenEnd
    // Advance past the token's newlines.
    while self.lineIdx < newlinePositions.count && newlinePositions[self.lineIdx] < tokenEnd {
      self.lineIdx += 1
    }
    if kind == popKind {
      stack.removeLast()
    } else {
      if let childPair = ${Name}Lexer.modeTransitions[mode]?[kind] {
        stack.append(childPair)
      }
    }
    let token = Token(pos: tokenPos, end: tokenEnd, linePos: linePos, lineIdx: lineIdx, kind: kind)
    func empty(_ at: Int, _ kind: ${Name}TokenKind) -> Token<${Name}TokenKind> {
      return Token(pos: at, end: at, linePos: linePos, lineIdx: lineIdx, kind: kind)
    }
    guard let lineBreak = ${Name}Lexer.modeLineBreaks[mode] else { // The mode is not line-aware.
      pending.append(token)
      return
    }
    let indentSpace = ${Name}Lexer.modeIndentSpaces[mode]
    if kind == lineBreak {
      pending.append(contentsOf: held)
      held.removeAll()
      if lineCounts { pending.append(empty(tokenPos, .end_of_line)) }
      pending.append(token)
      lineCounts = false
      isLineStart = true
    } else if ${Name}Lexer.modeLineIgnores[mode]?.contains(kind) ?? false {
      if isLineStart && indentSpace != nil {
        held.append(token) // The line may not count.
      } else {
        pending.append(token)
      }
    } else { // The token counts.
      if isLineStart, let indentSpace = indentSpace {
        let spaceToken: Token<${Name}TokenKind>? = (held.first?.kind == indentSpace) ? held.first : nil
        let space: Range<Int> = spaceToken.map { t in t.pos..<t.end } ?? 0..<0
        let text = source.text
        if text[space] != text[levels.last!] {
          var countDedents = 0
          while !text[space].starts(with: text[levels.last!]) {
            levels.removeLast()
            countDedents += 1
          }
          if space.count > levels.last!.count { // Deeper than the innermost remaining level.
            levels.append(space)
            let at = spaceToken!.pos
            for _ in 0..<countDedents { pending.append(empty(at, .dedent)) }
            pending.append(empty(at, .indent))
            pending.append(contentsOf: held)
          } else {
            pending.append(contentsOf: held)
            for _ in 0..<countDedents { pending.append(empty(tokenPos, .dedent)) }
          }
          held.removeAll()
        }
      }
      pending.append(contentsOf: held)
      held.removeAll()
      pending.append(token)
      lineCounts = true
      isLineStart = false
    }
  }

  private static let modeTransitions: Dictionary<${Name}LexMode, Dictionary<TokenKind, (${Name}LexMode, TokenKind?)>> = ${mode_transitions_dict}

  private static let modeLineBreaks: Dictionary<${Name}LexMode, TokenKind> = ${mode_line_breaks_dict}

  private static let modeLineIgnores: Dictionary<${Name}LexMode, Set<TokenKind>> = ${mode_line_ignores_dict}

  private static let modeIndentSpaces: Dictionary<${Name}LexMode, TokenKind> = ${mode_indent_spaces_dict}
}
'''


def swift_kind_syms(kinds:Iterable[str]) -> dict[str,str]:
  '''
  Return the Swift enum case name for each token kind.
  The cases of the generated `TokenKind` enum are declared in sorted order of these names, which determines their raw values.
  '''
  kind_syms = { kind : swift_safe_sym(kind) for kind in kinds }
  kind_syms['incomplete'] = 'incomplete'
  assert len(kind_syms) == len(set(kind_syms.values()))
  return kind_syms


class SwiftEnum:
  def __init__(self, string:str):
    self.string = string

  @property
  def swift_repr(self) -> str: return '.' + self.string


swift_escapes:dict[str, str] = {
  '\0' : '\\0',
  '\\' : '\\\\',
  '\t' : '\\t',
  '\n' : '\\n',
  '\r' : '\\r',
  '"'  : '\\"',
}

def swift_escape_literal_char(c:str) -> str:
  try:
    return swift_escapes[c]
  except KeyError: pass
  if c.isprintable():
    return c
  return '\\u{{{:x}}}'.format(ord(c))

def swift_esc_str(string:str) -> str:
  return ''.join(swift_escape_literal_char(c) for c in string)

def swift_repr(obj:Any, indent:int=0) -> str:
  if isinstance(obj, int): return repr(obj)
  if isinstance(obj, str): return f'"{swift_esc_str(obj)}"'
  if isinstance(obj, SwiftEnum): return obj.swift_repr
  if isinstance(obj, tuple): return f'({",".join(swift_repr(el) for el in obj)})'
  if isinstance(obj, list): return f'[{", ".join(swift_repr(el) for el in obj)}]' # An array literal, which also initializes a Set.
  if isinstance(obj, dict):
    items = ''.join(swift_repr_kv(kv, indent=indent+2) for kv in obj.items())
    ind = ' ' * indent
    return f'[\n{items}{ind}]' if obj else '[:]'
  raise ValueError(obj)

def swift_repr_kv(kv:tuple[Any, Any], indent:int) -> str:
  ind = ' ' * indent
  return f'{ind}{swift_repr(kv[0], indent=indent)}:{swift_repr(kv[1], indent=indent)},\n'


def swift_safe_sym(name:str) -> str:
  'Return `name` changed as necessary to be a valid Swift identifier.'
  name = re.sub(r'[^\w]', '_', name)
  if name[0].isdigit():
    name = '_' + name
  if name in swift_reserved_syms:
    name += '_'
  return name

